using System.Collections.Generic;
using App.Core.Contracts;
using App.Core.Metrics;

namespace App.Core.Analysis
{
    /// <summary>
    /// All participant-facing wording produced by local code. Follows CONCEPT 5.3: "deviation from your baseline",
    /// "experimental", "you reported". A test scans these strings for forbidden claims.
    /// </summary>
    public static class ReportText
    {
        public const string IndicatorLabel = "Experimental baseline-deviation indicator";
        public const string IndicatorDisclaimer = "Experimental heuristic based on deviation from your own baseline. Not a validated measure and not a medical assessment.";

        public static string FallbackNarrative(Reconciliation r, DataSource source)
        {
            string body;
            switch (r)
            {
                case Reconciliation.AgreeHigh:
                    body = "You reported feeling strained, and your eye movements also changed compared with how you started.";
                    break;
                case Reconciliation.WordsOnly:
                    body = "You reported feeling strained. The eye signals did not show a strong change from your baseline; your report counts.";
                    break;
                case Reconciliation.SignalsOnly:
                    body = "Your eye movements changed from your baseline, but you reported feeling fine. A short break is available if you want one.";
                    break;
                case Reconciliation.AgreeLow:
                    body = "You reported feeling fine, and your eye movements stayed close to your baseline.";
                    break;
                default:
                    body = "No usable eye data for this session, so this summary is based on what you reported.";
                    break;
            }
            return body + " " + SourceSentence(source) + " Generated by local rules, not by AI.";
        }

        public static string SourceSentence(DataSource source)
        {
            switch (source)
            {
                case DataSource.Live: return "Based on live eye tracking.";
                case DataSource.Replay: return "Based on replayed eye data, not a live measurement.";
                default: return "Based on synthetic data, not a measurement of you.";
            }
        }

        public static List<string> Limitations(SessionSummary s)
        {
            var list = new List<string> { "Experimental heuristic; not a medical assessment and not validated fatigue detection." };
            if (s.DataSource != DataSource.Live) list.Add(SourceSentence(s.DataSource));
            if (s.Quality.Status == QualityStatus.InsufficientData) list.Add("Not enough valid eye data; the indicator is unavailable.");
            if (s.Baseline.LowConfidence) list.Add(BaselinePolicy.LowConfidenceWording);
            if (!s.Capabilities.Pupil || !s.Capabilities.Openness) list.Add("Pupil size and blinks are not available on this headset.");
            if (list.Count > 5) list.RemoveRange(5, list.Count - 5);
            return list;
        }

        public static string ReconciliationLabel(Reconciliation r)
        {
            switch (r)
            {
                case Reconciliation.AgreeHigh: return "Your report and the eye signals both point to strain.";
                case Reconciliation.WordsOnly: return "You reported strain; the eye signals did not show a strong change. Your report counts.";
                case Reconciliation.SignalsOnly: return "Eye signals changed, but you reported feeling fine. Want a short break?";
                case Reconciliation.AgreeLow: return "Your report and the eye signals both look close to your baseline.";
                default: return "No usable eye data: based on your report only.";
            }
        }

        public static string ChipLabel(Chip c)
        {
            switch (c)
            {
                case Chip.TiredEyes: return "tired eyes";
                case Chip.TiredMind: return "tired mind";
                case Chip.Tense: return "tense";
                case Chip.Restless: return "restless";
                case Chip.Overstimulated: return "overstimulated";
                case Chip.LowEnergy: return "low energy";
                case Chip.WantQuiet: return "want quiet";
                case Chip.WantNature: return "want nature";
                case Chip.WantDim: return "want dim light";
                case Chip.WantMovement: return "want movement";
                default: return c.ToString();
            }
        }

        public static string ObservationLabel(ObservationCode code)
        {
            switch (code)
            {
                case ObservationCode.GazeSpeedChanged: return "Gaze speed differed from your baseline";
                case ObservationCode.GazeSpreadChanged: return "Gaze spread differed from your baseline";
                case ObservationCode.ProbeSlower: return "Target-following was slower than your baseline";
                case ObservationCode.ProbeLessAccurate: return "Target-following was less precise than your baseline";
                case ObservationCode.ProbeMoreMisses: return "More targets were missed than at baseline";
                case ObservationCode.HeadMoreActive: return "Head moved more than at baseline";
                case ObservationCode.WithinBaseline: return "Eye-movement measures stayed close to your baseline";
                case ObservationCode.NoBaseline: return "No baseline: raw measures only";
                case ObservationCode.DataQualityLimited: return "Data quality was too limited for comparisons";
                default: return code.ToString();
            }
        }
    }
}
